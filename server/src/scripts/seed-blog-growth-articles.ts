async function seedBlogGrowthArticles() {
  const db = new sqlite3.Database(dbPath)
  const run = (sql: string, params: unknown[] = []) => new Promise<void>((resolve, reject) => {
    db.run(sql, params, (error) => {
      if (error) reject(error)
      else resolve()
    })
  })

  try {
    console.log('🔄 Добавление SEO-статей для роста блога...')

    for (const article of articles) {
      await run(`
        INSERT OR IGNORE INTO articles (
          title, slug, excerpt, content, image_url, category, tags, author, published
        ) VALUES (?, ?, ?, ?, ?, ?, ?, 'ВозьмиМеня', 1)
      `, [
        article.title,
        article.slug,
        article.excerpt,
        article.content,
        article.imageUrl,
        article.category,
        article.tags,
      ])
    }

    console.log(`✅ Готово: обработано статей ${articles.length}`)
  } finally {
    await new Promise<void>((resolve, reject) => {
      db.close((error) => {
        if (error) reject(error)
        else resolve()
      })
    })
  }
}

